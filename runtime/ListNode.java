/**
 * LeetCode's singly-linked list node, verbatim. Lives in the default package and on the
 * workspace classpath so pasted solutions compile without edits.
 */
public class ListNode {
    public int val;
    public ListNode next;
    public ListNode() {}
    public ListNode(int val) { this.val = val; }
    public ListNode(int val, ListNode next) { this.val = val; this.next = next; }
}
